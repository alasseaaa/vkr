def _normalize_reminder_items(raw):
    out = []
    for x in raw or []:
        if isinstance(x, str):
            t = x.strip()
            if t:
                out.append(t)
        elif isinstance(x, dict):
            t = (x.get("prompt_text") or "").strip()
            if t:
                out.append(t)
    return out


def _merged_from_json_reminders(raw):
    parts = _normalize_reminder_items(raw)
    return " ".join(parts) if parts else ""


class Command(BaseCommand):
    help = (
        "Заменяет напоминания RecommendationReminder для рекомендаций: "
        "одна запись на рекомендацию; из JSON несколько строк объединяются в один текст."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "json_path",
            nargs="?",
            default=None,
            help="Необязательный путь к JSON (recommendations[].id, reminders — список строк).",
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Только вывести план, без записи в БД.",
        )

    def handle(self, *args, **options):
        dry = options["dry_run"]
        path = options["json_path"]

        if path:
            p = Path(path)
            if not p.is_file():
                self.stderr.write(self.style.ERROR(f"Файл не найден: {p}"))
                return
            with open(p, encoding="utf-8") as f:
                data = json.load(f)
            by_id = {}
            for item in data.get("recommendations") or []:
                rid = item.get("id")
                if rid is None:
                    continue
                merged = _merged_from_json_reminders(item.get("reminders"))
                if merged:
                    by_id[int(rid)] = merged
        else:
            by_id = dict(REMINDERS)

        total_new = 0
        for rid, merged in sorted(by_id.items()):
            merged = (merged or "").strip()
            if not merged:
                continue
            try:
                rec = Recommendation.objects.get(pk=rid)
            except Recommendation.DoesNotExist:
                self.stdout.write(self.style.WARNING(f"Пропуск: рекомендация id={rid} не найдена"))
                continue

            existing = rec.reminders.count()
            if dry:
                self.stdout.write(
                    f"[dry-run] id={rid} «{rec.title[:50]}…»: удалить {existing}, создать 1"
                )
                total_new += 1
                continue

            rec.reminders.all().delete()
            RecommendationReminder.objects.create(
                recommendation=rec,
                prompt_text=merged,
                interval_days=7,
                is_active=True,
            )
            total_new += 1
            self.stdout.write(
                self.style.SUCCESS(
                    f"id={rid}: заменено напоминаний — было {existing}, стало 1"
                )
            )

        self.stdout.write(self.style.SUCCESS(f"Готово. Всего создано записей напоминаний: {total_new}"))
